#!/usr/bin/env python3
"""Regenerate src/airports-data.ts from OurAirports (public domain).

Usage: python3 -I packages/domain/scripts/build-airports.py path/to/airports.csv
Download airports.csv from https://davidmegginson.github.io/ourairports-data/airports.csv
Keeps large/medium airports with scheduled passenger service and an IATA code.
"""

import csv
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "airports-data.ts"

rows = []
with open(sys.argv[1], encoding="utf-8") as source:
    for row in csv.DictReader(source):
        if row["scheduled_service"] != "yes" or not row["iata_code"] or row["type"] not in ("large_airport", "medium_airport"):
            continue
        rows.append([
            row["iata_code"],
            row["name"],
            row["municipality"],
            row["iso_region"].split("-", 1)[-1],
            row["iso_country"],
            round(float(row["latitude_deg"]), 3),
            round(float(row["longitude_deg"]), 3),
            1 if row["type"] == "large_airport" else 0,
        ])
rows.sort()
body = ",\n".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in rows)
OUT.write_text(
    "// Generated by scripts/build-airports.py from OurAirports (public domain). Do not edit.\n"
    "// [iata, name, city, region, country, latitude, longitude, large]\n"
    "export const airportRows:[string,string,string,string,string,number,number,0|1][]=[\n"
    f"{body}\n];\n",
    encoding="utf-8",
)
print(f"Wrote {len(rows)} airports to {OUT}")
